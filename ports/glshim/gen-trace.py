"""Generate the GL tracing interposer: trace_stubs.s, trace_tab.c and the OpenGLES stub .tbd.

Usage: python3 -I glshim/gen-trace.py build/glnames.txt
"""
import os
import sys

names = [l.strip() for l in open(sys.argv[1]) if l.strip()]
root = os.path.dirname(os.path.abspath(__file__))

asm = ["\t.syntax unified", "\t.arm", "\t.text", "\t.align 2"]
for i, n in enumerate(names):
    s = n[1:]  # drop leading underscore (C name)
    asm += [
        "\t.private_extern _j1t_%s" % s,
        "_j1t_%s:" % s,
        "\tpush {r4, lr}",
        "\tmovw r0, #%d" % i,
        "\tbl _j1_trace",
        "\tmov r0, #0",
        "\tmov r1, #0",
        "\tpop {r4, pc}",
    ]
open(os.path.join(root, "trace_stubs.s"), "w").write("\n".join(asm) + "\n")

c = ["/* generated by gen-trace.py */", "typedef void (*fn)(void);"]
for n in names:
    s = n[1:]
    c.append("extern void %s(void) __attribute__((weak_import));" % s)
    c.append("extern void j1t_%s(void);" % s)
c.append("const char *const j1_names[%d] = {" % len(names))
c += ['    "%s",' % n[1:] for n in names]
c.append("};")
c.append("const int j1_nnames = %d;" % len(names))
c.append("struct j1_interpose { fn rep; fn orig; };")
c.append('__attribute__((used, section("__DATA,__interpose"))) struct j1_interpose j1_tab[%d] = {' % len(names))
c += ["    { j1t_%s, %s }," % (n[1:], n[1:]) for n in names]
c.append("};")
open(os.path.join(root, "trace_tab.c"), "w").write("\n".join(c) + "\n")

tbd = os.path.join(root, "sdk/System/Library/Frameworks/OpenGLES.framework/OpenGLES.tbd")
os.makedirs(os.path.dirname(tbd), exist_ok=True)
open(tbd, "w").write(
    "--- !tapi-tbd\ntbd-version:     4\ntargets:         [ armv7-ios ]\n"
    "install-name:    '/System/Library/Frameworks/OpenGLES.framework/OpenGLES'\ncurrent-version: 1.0.0\n"
    "exports:\n  - targets:         [ armv7-ios ]\n    symbols:         [ %s ]\n...\n" % ", ".join(names)
)
print("generated", len(names))
