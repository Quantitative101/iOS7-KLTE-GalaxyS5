"""Generate the fake GL macro context: ctx_stubs.s (generic slot tracers) and ctx_tab.c (table fill).

Usage: python3 -I glshim/gen-ctx.py build/gl-dispatch.txt build/glnames.txt
Slots named in the dispatch map point at the matching _j1t_<name> stub from trace_stubs.s; every other 4-byte slot between
0x3c and 0xffc gets a generic tracer that logs its offset.
"""
import os
import sys

root = os.path.dirname(os.path.abspath(__file__))
known = {l.strip() for l in open(sys.argv[2]) if l.strip()}
import re

impls = set(re.findall(r"\bj1i_(gl\w+)\(", open(os.path.join(root, "impl.c")).read()))
mapping = {}
for line in open(sys.argv[1]):
    p = line.split()
    if len(p) == 2 and p[1] != "?" and p[0] in known:
        off = int(p[1], 16)
        name = p[0][1:]
        # aliases (OES/EXT/ARB) share one slot: prefer any alias that has an implementation
        if off not in mapping or (mapping[off] not in impls and name in impls):
            mapping[off] = name
lo, hi = 0x14, 0x1000
asm = ["\t.syntax unified", "\t.arm", "\t.text", "\t.align 2"]
c = ["/* generated by gen-ctx.py */", "typedef void (*fn)(void);"]
fills = []
for off in range(lo, hi, 4):
    if off in mapping and mapping[off] in impls:
        c.append("extern void j1i_%s(void);" % mapping[off])
        fills.append("    t[0x%x / 4] = (unsigned)j1i_%s;" % (off, mapping[off]))
    elif off in mapping:
        c.append("extern void j1t_%s(void);" % mapping[off])
        fills.append("    t[0x%x / 4] = (unsigned)j1t_%s;" % (off, mapping[off]))
    else:
        asm += [
            "\t.private_extern _j1s_%x" % off,
            "_j1s_%x:" % off,
            "\tpush {r0-r3, r4, lr}",
            "\tmov r1, lr",
            "\tmov r2, sp",
            "\tmovw r0, #0x%x" % off,
            "\tbl _j1_trace_slot",
            "\tpop {r0-r3, r4, lr}",
            "\tmov r0, #0",
            "\tmov r1, #0",
            "\tbx lr",
        ]
        c.append("extern void j1s_%x(void);" % off)
        fills.append("    t[0x%x / 4] = (unsigned)j1s_%x;" % (off, off))
c.append("void j1_fill_ctx(unsigned *t)")
c.append("{")
c += fills
c.append("}")
open(os.path.join(root, "ctx_stubs.s"), "w").write("\n".join(asm) + "\n")
open(os.path.join(root, "ctx_tab.c"), "w").write("\n".join(c) + "\n")
print("mapped", len(mapping), "slots", (hi - lo) // 4)
